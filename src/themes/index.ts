/** Applies a theme by writing semantic design tokens onto the document root. */
export function applyTheme(themeId: string, appearance: Appearance): void {
  if (typeof document === 'undefined') return;
  const theme = getTheme(themeId);
  const palette = theme[appearance];
  const status = statusPalettes[appearance];
  const root = document.documentElement;

  const tokens: Record<string, string> = {
    '--background': palette.background,
    '--surface': palette.surface,
    '--elevated': palette.elevated,
    '--foreground': palette.foreground,
    '--muted-foreground': palette.mutedForeground,
    '--primary': palette.primary,
    '--primary-foreground': palette.primaryForeground,
    '--secondary': palette.secondary,
    '--secondary-foreground': palette.secondaryForeground,
    '--accent': palette.accent,
    '--accent-foreground': palette.accentForeground,
    '--border': palette.border,
    '--input': palette.input,
    '--ring': palette.ring,
    '--nav': palette.nav,
    '--correct': status.correct,
    '--correct-bg': status.correctBg,
    '--correct-border': status.correctBorder,
    '--incorrect': status.incorrect,
    '--incorrect-bg': status.incorrectBg,
    '--incorrect-border': status.incorrectBorder,
    '--unanswered': status.unanswered,
    '--unanswered-bg': status.unansweredBg,
    '--unanswered-border': status.unansweredBorder,
    '--excluded': status.excluded,
    '--excluded-bg': status.excludedBg,
    '--excluded-border': status.excludedBorder,
    '--warning': status.warning,
    '--destructive': status.destructive,
    '--destructive-foreground': status.destructiveForeground,
  };

  for (const [name, value] of Object.entries(tokens)) {
    root.style.setProperty(name, value);
  }

  root.dataset.theme = themeId;
  root.dataset.appearance = appearance;
  root.classList.toggle('dark', appearance === 'dark');
  root.style.colorScheme = appearance;

  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.setAttribute('content', palette.background);
}

export function resolveAppearance(
  mode: 'light' | 'dark' | 'system',
  prefersDark: boolean,
): Appearance {
  if (mode === 'system') return prefersDark ? 'dark' : 'light';
  return mode;
}
